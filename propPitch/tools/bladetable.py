#!/usr/bin/env python3
"""Regenerate ``propPitch/bladeTable.py`` from a KSP install's part configs:
the aero curves and constants of every stock rotor/propeller blade
(``SquadExpansion/Serenity/Parts/Propellers``) and Physics.cfg's lifting-
surface multipliers.

    ./propPitch/tools/bladetable.py [GameData-parent]   # default: the farm's base copy

``tests/testBladeModel.py`` checks the committed table against the farm's
base copy when it exists, so a game update that changes a blade disagrees.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "propPitch", "bladeTable.py")
CURVES = ("liftCurve", "liftMachCurve", "dragCurve", "dragMachCurve")


def strip(text):
    return re.sub(r"//[^\n]*", "", text)


def block(text, name):
    """The body of the first ``name { ... }`` in ``text``, or None."""
    m = re.search(r"\b%s\s*\{" % re.escape(name), text)
    if not m:
        return None
    depth, i = 1, m.end()
    while depth:
        depth += {"{": 1, "}": -1}.get(text[i], 0)
        i += 1
    return text[m.end():i - 1]


def value(text, key):
    m = re.search(r"^\s*%s\s*=\s*(.+?)\s*$" % re.escape(key), text, re.M | re.I)
    return m.group(1) if m else None


def parse_part(path):
    text = strip(open(path, encoding="utf-8-sig").read())
    name = value(text, "name")
    # The ModuleControlSurface block.
    body = None
    for m in re.finditer(r"MODULE\s*\{", text):
        b = block(text[m.start():], "MODULE")
        if b and re.search(r"name\s*=\s*ModuleControlSurface", b):
            body = b
            break
    if body is None:
        return None
    entry = {"dlc": float(value(body, "deflectionLiftCoeff") or 1.5),
             "area": float(value(body, "ctrlSurfaceArea") or 0.5),
             # Deploy Angle is limited to +/-1.5 x this (ModuleControlSurface
             # .OnStart; the field's default is 15).
             "range": float(value(body, "ctrlSurfaceRange") or 15.0)}
    off = value(body, "velocityOffset") or "0,0,0"
    entry["offset"] = tuple(float(x) for x in off.split(","))
    col = value(text, "CoLOffset") or "0,0,0"
    entry["col"] = tuple(float(x) for x in col.split(","))
    entry["displace"] = (value(body, "displaceVelocity") or "false").lower() == "true"
    for c in CURVES:
        b = block(body, c)
        keys = []
        for line in re.findall(r"key\s*=\s*([^\n]+)", b or ""):
            nums = [float(x) for x in line.split()]
            while len(nums) < 4:
                nums.append(0.0)
            keys.append(tuple(nums[:4]))
        entry[c] = keys
    return name, entry


def main():
    base = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        ROOT, "testInstances", "base")
    pdir = os.path.join(base, "GameData", "SquadExpansion", "Serenity",
                        "Parts", "Propellers")
    table = {}
    for f in sorted(os.listdir(pdir)):
        if f.endswith(".cfg"):
            got = parse_part(os.path.join(pdir, f))
            if got:
                table[got[0]] = got[1]
    phys = strip(open(os.path.join(base, "Physics.cfg")).read())
    lift = float(value(phys, "liftMultiplier"))
    drag = float(value(phys, "liftDragMultiplier"))
    with open(OUT, "w") as fh:
        fh.write('"""Stock blade aero data, generated by propPitch/tools/'
                 'bladetable.py\nfrom the game\'s part configs and Physics.cfg: '
                 'do not edit by hand.\n\nEach curve is a list of FloatCurve '
                 'keys (time, value, in-tangent,\nout-tangent).  Lift and drag '
                 'curves are keyed on |sin(incidence)|, the\nMach curves on the '
                 'Mach number of the blade\'s velocity point.\n"""\n\n')
        fh.write("LIFT_MULTIPLIER = %r\nLIFT_DRAG_MULTIPLIER = %r\n\n"
                 % (lift, drag))
        fh.write("BLADES = {\n")
        for name, e in table.items():
            fh.write("    %r: {\n" % name)
            for k in ("dlc", "area", "range", "offset", "col", "displace"):
                fh.write("        %r: %r,\n" % (k, e[k]))
            for c in CURVES:
                fh.write("        %r: [\n" % c)
                for key in e[c]:
                    fh.write("            (%s),\n" % ", ".join(repr(x) for x in key))
                fh.write("        ],\n")
            fh.write("    },\n")
        fh.write("}\n")
    print("wrote %s: %s" % (OUT, ", ".join(table)))


if __name__ == "__main__":
    main()
